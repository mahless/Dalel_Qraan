def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    data_path = os.path.join(script_dir, '..', 'src', 'data', 'hadith', 'hadith_daily.json')
    
    with open(data_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    fixed_count = 0
    not_found = []
    
    for item in data:
        hid = item['id']
        if hid in CORRECT_EXPLANATIONS:
            item['explanation'] = CORRECT_EXPLANATIONS[hid]
            fixed_count += 1
    
    # Verify all corrections were applied
    for hid in CORRECT_EXPLANATIONS:
        found = any(item['id'] == hid for item in data)
        if not found:
            not_found.append(hid)
    
    if not_found:
        print(f"WARNING: IDs not found in data: {not_found}")
    
    # Write back
    with open(data_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"Fixed {fixed_count} hadith explanations out of {len(data)} total.")
    print(f"Corrections dictionary had {len(CORRECT_EXPLANATIONS)} entries.")

if __name__ == '__main__':
    main()
